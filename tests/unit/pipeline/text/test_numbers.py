import pytest

from subvoicer.pipeline.text.numbers import numbers_to_words, percent_word


@pytest.mark.parametrize(
    ("text", "spoken"),
    [
        ("У меня 3 патрона.", "У меня три патрона."),
        ("Сейчас 2077 год", "Сейчас две тысячи семьдесят семь год"),
        ("Встретимся в 22:30.", "Встретимся в двадцать два тридцать."),
        ("В 7:00 утра", "В семь ноль ноль утра"),
        ("Лифт на 45-м этаже", "Лифт на сорок пятом этаже"),
        ("3-я глава", "третья глава"),
        ("со 2-го раза", "со второго раза"),
        ("в 90-х годах", "в девяностых годах"),
        ("Цена выросла на 30%.", "Цена выросла на тридцать процентов."),
        ("21% и 2 %", "двадцать один процент и два процента"),
        ("12%", "двенадцать процентов"),
        ("3,5 литра", "три целых пять десятых литра"),
        ("Код 0142", "Код ноль один четыре два"),
        ("Позвони 555-0142", "Позвони пятьсот пятьдесят пять-ноль один четыре два"),
        ("Без чисел", "Без чисел"),
    ],
)
def test_numbers(text: str, spoken: str) -> None:
    assert numbers_to_words(text) == spoken


def test_percent_word() -> None:
    assert [
        percent_word(n) for n in ("1", "2", "5", "11", "14", "21", "22", "25", "101", "3.5")
    ] == [
        "процент",
        "процента",
        "процентов",
        "процентов",
        "процентов",
        "процент",
        "процента",
        "процентов",
        "процент",
        "процента",
    ]
